const W = 960;
const H = 520;
const russia = feature(topo, topo.objects.countries).features.find((f) => String(f.id) === '643');
const projection = geoConicEqualArea().parallels([52, 64]).rotate([-100, 0]).center([0, 62]).scale(1);
projection.fitExtent([[10, 10], [W - 10, H - 10]], russia);
const path = geoPath(projection).digits(1);

const out = {
  w: W,
  h: H,
  path: path(russia),
  regions: REGIONS.map(([name, lon, lat]) => {
    const [x, y] = projection([lon, lat]);
    return { name, x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 };
  }),
};
fs.writeFileSync(new URL('../src/data/russia-map.json', import.meta.url), JSON.stringify(out));
