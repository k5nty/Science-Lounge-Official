export const dictionaries = { ru, en };

export function translator(lang) {
  const dict = dictionaries[lang] || ru;
  return (key, vars) => {
    let s = dict[key] ?? ru[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
}
